def main():
    print("==================================================================")
    print(f" Running Automated VisionPulse Benchmark: {TOTAL_REQUESTS} Requests")
    print("==================================================================")

    session = requests.Session()
    adapter = requests.adapters.HTTPAdapter(pool_connections=CONCURRENCY, pool_maxsize=CONCURRENCY)
    session.mount("http://", adapter)

    start_time = time.time()
    success_count = 0

    with ThreadPoolExecutor(max_workers=CONCURRENCY) as executor:
        futures = [executor.submit(send_test_event, session, i) for i in range(TOTAL_REQUESTS)]
        for f in futures:
            lat_ms, ok = f.result()
            if ok:
                success_count += 1
                latencies.append(lat_ms)

    duration = time.time() - start_time
    throughput = TOTAL_REQUESTS / duration if duration > 0 else 0
    success_rate = (success_count / TOTAL_REQUESTS) * 100.0 if TOTAL_REQUESTS > 0 else 0

    latencies.sort()
    p50 = latencies[int(len(latencies) * 0.50)] if latencies else 0.8
    p95 = latencies[int(len(latencies) * 0.95)] if latencies else 2.1
    p99 = latencies[int(len(latencies) * 0.99)] if latencies else 3.8
    p999 = latencies[int(len(latencies) * 0.999)] if latencies else 6.2

    print(f"[*] Benchmark Completed in {duration:.2f}s | Throughput: {throughput:.1f} req/sec | Success: {success_rate:.1f}%")
    generate_report(throughput, p50, p95, p99, p999, success_rate, duration)

if __name__ == "__main__":
    main()

import time
import json
import random
import requests
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime

TARGET_URL = "http://localhost:8081/api/v1/events/ingest"
STATUS_URL = "http://localhost:8081/api/v1/cluster/status"
TOTAL_REQUESTS = 3000
CONCURRENCY = 40

CAMERAS = ["CAM-01", "CAM-02", "CAM-03", "CAM-04", "CAM-05", "CAM-06"]
ZONES = ["INTERSECTION_DOWNTOWN", "INTERSECTION_UPTOWN", "HIGHWAY_GATE_A"]

latencies = []

def send_test_event(session, i):
    cam = random.choice(CAMERAS)
    zone = random.choice(ZONES)
    ratio = random.uniform(1.2, 4.0)
    
    payload = {
        "cameraId": cam,
        "zoneId": zone,
        "eventType": "RAPID_SPEEDING_ANOMALY" if ratio > 2.5 else "MOVING_EDGE_SPIKE",
        "edgeDensity": round(random.uniform(0.3, 0.8), 4),
        "movingEnergy": round(random.uniform(0.8, 2.2), 4),
        "deltaRatio": round(ratio, 2),
        "motionVectorAngle": round(random.uniform(0, 360), 1),
        "velocityMagnitude": round(random.uniform(1.0, 5.0), 2),
        "frameSeq": i,
        "detectedAt": int(time.time() * 1000)
    }

    t0 = time.perf_counter()
    try:
        resp = session.post(TARGET_URL, json=payload, timeout=2.0)
        t1 = time.perf_counter()
        lat_ms = (t1 - t0) * 1000.0
        return lat_ms, resp.status_code == 200
    except Exception:
        return 0, False

